using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.ViewEngines;
using Microsoft.AspNetCore.Mvc.Rendering;
using Microsoft.AspNetCore.Mvc.ViewFeatures;
using Microsoft.AspNetCore.Mvc.ModelBinding;
using Microsoft.AspNetCore.Routing;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.FileProviders;
using _2Korriku.Models;
using _2Korriku.Data;
using _2Korriku.Services;
var root=Path.GetFullPath("../..");
var builder=WebApplication.CreateBuilder(args);
builder.Services.AddControllersWithViews().AddApplicationPart(typeof(CoachActivityReport).Assembly);
builder.Services.AddScoped(_=>new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().Options));
builder.Services.AddScoped<ClubBranding>();
var app=builder.Build();
app.UseStaticFiles(new StaticFileOptions{FileProvider=new PhysicalFileProvider(Path.Combine(root,"wwwroot"))});
app.MapGet("/preview/{kind}",async (HttpContext http,string kind)=>{
    var report=kind=="report";
    var ac=new ActionContext(http,new RouteData(),new Microsoft.AspNetCore.Mvc.Abstractions.ActionDescriptor());
    ac.RouteData.Values["controller"]=report?"Reports":"Coaches";
    ac.RouteData.Values["action"]=report?"CoachActivity":"Index";
    var engine=http.RequestServices.GetRequiredService<ICompositeViewEngine>();
    var result=engine.GetView(null,report?"/Views/Reports/CoachActivity.cshtml":"/Views/Coaches/RoleChoice.cshtml",false);
    if(!result.Success)return Results.Text(string.Join("\n",result.SearchedLocations));
    var data=new ViewDataDictionary(new EmptyModelMetadataProvider(),new ModelStateDictionary());
    if(report)data.Model=new CoachActivityReport{From=new(2026,10,1),To=new(2026,10,22),Rows=[new("Trajneri A",12,24,2,14,new DateTime(2026,10,22,8,30,0,DateTimeKind.Utc)),new("Trajneri B",10,15,1,12,new DateTime(2026,10,21,9,0,0,DateTimeKind.Utc)),new("Trajneri C",8,9,1,10,new DateTime(2026,10,20,8,0,0,DateTimeKind.Utc))]};
    using var sw=new StringWriter();
    var temp=new TempDataDictionary(http,http.RequestServices.GetRequiredService<ITempDataProvider>());
    var vc=new ViewContext(ac,result.View,data,temp,sw,new HtmlHelperOptions());
    await result.View.RenderAsync(vc);
    var icons=await File.ReadAllTextAsync(Path.Combine(root,"Views/Shared/_Icons.cshtml"));
    return Results.Content("<!doctype html><html><head><meta charset='utf-8'><link rel='stylesheet' href='/lib/bootstrap/dist/css/bootstrap.min.css'><link rel='stylesheet' href='/css/site.css'></head><body style='padding:35px;background:#f5f7fa'>"+icons+sw+"</body></html>","text/html");
});
app.MapControllerRoute("default","{controller}/{action}/{id?}");
app.Run("http://127.0.0.1:5199");
