const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
    const url = process.argv[2];
    const browser = await chromium.launch({headless:true, executablePath:process.env.MANUAL_CHROME || undefined});
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    const output=process.env.MANUAL_SCREENSHOTS || path.join(__dirname,'artifacts');fs.mkdirSync(output,{recursive:true});
    try {
        await page.goto(url+'/Identity/Account/Login');
        await page.locator('input[name="Input.Email"]').fill('admin@manual.test');
        await page.locator('input[name="Input.Password"]').fill('ManualTest123!');
        await Promise.all([page.waitForURL(u=>!u.pathname.endsWith('/Login')),page.locator('button[type=submit]').click()]);
        await page.goto(url+'/Help');
        await page.locator('.manual-table').waitFor();
        assert(await page.locator('.manual-table tbody tr').count()>50,'Substantial manual coverage for admin');
        await page.screenshot({path:path.join(output,'manual-desktop.png')});
        await page.locator('#manual-query').fill('si ta korrigjoj borxhin');
        await Promise.all([page.waitForURL(/q=/),page.locator('.manual-search button').click()]);
        assert(await page.locator('a[href*="Payments.CorrectFee"]').count()>0,'Debt search finds correction');
        await page.locator('a[href*="Payments.CorrectFee"]').click();
        assert((await page.locator('.manual-article').innerText()).includes('përfundimtare, jo diferencën'));
        await page.goto(url+'/Leagues/Edit');
        await page.locator('.help-inline-button').first().waitFor();
        await page.locator('[name=Name]').fill('UNSAVED MANUAL TEST');
        let posts=0;page.on('request',r=>{if(r.method()==='POST')posts++;});
        await page.locator('[data-help-open]').click();
        await page.locator('#context-help[open]').waitFor();
        assert((await page.locator('#context-help').innerText()).includes('8+1'));
        assert(await page.locator('#help-form-list .help-form-row').count()>0);
        await page.screenshot({path:path.join(output,'manual-context-desktop.png')});
        await page.keyboard.press('Escape');
        assert(await page.locator('[data-help-open]').evaluate(e=>e===document.activeElement),'Close restores focus');
        await page.locator('.help-inline-button').first().click();
        await page.locator('#help-tour:not([hidden])').waitFor();
        assert.equal(await page.locator('.help-field-highlight').count(),1);
        assert((await page.locator('#help-tour-title').innerText()).includes('Emri'));
        await page.screenshot({path:path.join(output,'manual-tour-desktop.png')});
        await page.locator('#help-tour-next').click();
        assert((await page.locator('#help-tour-count').innerText()).includes('2 NGA'));
        await page.keyboard.press('Escape');
        assert.equal(await page.locator('.help-field-highlight').count(),0);
        assert.equal(await page.locator('[name=Name]').inputValue(),'UNSAVED MANUAL TEST');
        assert.equal(posts,0,'Help never submits or saves forms');
        await page.setViewportSize({width:390,height:844});
        await page.locator('[data-help-open]').click();
        const drawer=await page.locator('#context-help').boundingBox();
        assert(drawer.x>=-1&&drawer.width<=391&&drawer.height<=845,'Drawer fits mobile viewport');
        assert.equal(await page.locator('#context-help').evaluate(e=>e.scrollWidth>e.clientWidth),false,'No horizontal drawer overflow');
        await page.screenshot({path:path.join(output,'manual-context-mobile.png')});
        await page.locator('#help-form-list button').first().click();
        const tour=await page.locator('#help-tour').boundingBox();assert(tour.x>=0&&tour.x+tour.width<=391);
        await page.screenshot({path:path.join(output,'manual-tour-mobile.png')});
        await page.keyboard.press('Escape');
        await page.goto(url+'/Help');
        assert(await page.locator('.manual-table').evaluate(e=>e.parentElement.scrollWidth>e.parentElement.clientWidth),'Mobile table scrolls horizontally');
        await page.screenshot({path:path.join(output,'manual-mobile.png')});
        assert.equal(errors.length,0,'No browser JavaScript errors: '+errors.join('; '));
        console.log('PASS: Search, contextual help, keyboard, form preservation, no submission, desktop and mobile');
    } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1);});
